"""
보상 함수 v1 — 하루 주문별 이익을 10만 원으로 나눈 값

[이 보상을 고른 이유]
1. 우리 프로젝트의 최종 목표(성공 척도)는 '30일 누적 주문별 이익'을 최대로 만드는 것입니다.
2. v1에서는 별도 벌점이나 복잡한 점수를 섞지 않고, 매일 생기는 '하루 주문별 이익'을
   그대로 보상으로 씁니다. 하루 이익을 30일 더하면 최종 목표와 완전히 똑같아지므로,
   에이전트가 목표와 어긋나는 엉뚱한 행동을 배우지 않게 하는 가장 단순한 출발점입니다.
3. 다만 하루 이익은 보통 11만~40만 원으로 숫자가 커서 신경망 학습이 흔들릴 수 있습니다.
   그래서 모든 날의 이익을 똑같이 10만 원(가정)으로 나눠, 하루 보상이 대략 1~4 사이의
   안정적인 크기가 되도록 맞췄습니다. (같은 값으로 나누므로 이익을 늘리는 방향은 그대로입니다.)
"""

# 숫자 설정은 검토와 수정이 쉽도록 파일 맨 위에 모아 둡니다.
REWARD_VERSION = "v1"
REWARD_SCALE_WON = 100_000.0  # 가정 (보상 1 = 하루 이익 10만 원; 하루 보상 약 1~4 수준)


def compute_reward(daily_profit: float) -> float:
    """하루 주문별 이익(원)을 10만 원(가정)으로 나눠 v1 보상을 돌려줍니다."""
    return float(daily_profit / REWARD_SCALE_WON)
